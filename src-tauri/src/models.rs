use chrono::{DateTime, Utc};
use serde::{Deserialize, Deserializer, Serialize};
use uuid::Uuid;

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "mode", rename_all = "snake_case")]
pub enum AuthMode {
    Password,
    Key { key_id: Uuid },
}

impl Default for AuthMode {
    fn default() -> Self {
        AuthMode::Password
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Server {
    pub id: Uuid,
    pub name: String,
    pub host: String,
    #[serde(default = "default_port")]
    pub port: u16,
    pub user: String,
    #[serde(default)]
    pub auth: AuthMode,
    #[serde(default)]
    pub color: Option<String>,
    pub created_at: DateTime<Utc>,
    #[serde(default)]
    pub last_used_at: Option<DateTime<Utc>>,
    /// True only when all verification steps passed after hardening
    /// (key auth works, drop-in installed, sshd reloaded, password-auth confirmed off).
    #[serde(default)]
    pub hardened: bool,
    #[serde(default)]
    pub hardened_at: Option<DateTime<Utc>>,
    /// Sidebar folder; None = "Ohne Ordner".
    #[serde(default)]
    pub folder_id: Option<Uuid>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Folder {
    pub id: Uuid,
    pub name: String,
    pub created_at: DateTime<Utc>,
}

fn default_port() -> u16 {
    22
}

/// Plain serde maps both a missing field and `null` to None; this keeps `null` as Some(None).
fn double_option<'de, D, T>(d: D) -> Result<Option<Option<T>>, D::Error>
where
    D: Deserializer<'de>,
    T: Deserialize<'de>,
{
    Option::<T>::deserialize(d).map(Some)
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NewServerInput {
    pub name: String,
    pub host: String,
    #[serde(default = "default_port")]
    pub port: u16,
    pub user: String,
    #[serde(default)]
    pub color: Option<String>,
    #[serde(default)]
    pub auth: AuthMode,
    #[serde(default)]
    pub folder_id: Option<Uuid>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct UpdateServerInput {
    pub id: Uuid,
    pub name: Option<String>,
    pub host: Option<String>,
    pub port: Option<u16>,
    pub user: Option<String>,
    /// Missing = unchanged, null = remove color.
    #[serde(default, deserialize_with = "double_option")]
    pub color: Option<Option<String>>,
    pub auth: Option<AuthMode>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct KeyInfo {
    pub id: Uuid,
    pub name: String,
    pub algorithm: String,
    pub public_openssh: String,
    pub private_path: String,
    pub public_path: String,
    pub created_at: DateTime<Utc>,
    /// SHA256 OpenSSH-style fingerprint, e.g. "SHA256:abc...=".
    /// Optional for backwards compat; filled on generate/import.
    #[serde(default)]
    pub fingerprint: Option<String>,
    /// True if the key was generated by terminalox; false if imported.
    #[serde(default)]
    pub origin_imported: bool,
}
